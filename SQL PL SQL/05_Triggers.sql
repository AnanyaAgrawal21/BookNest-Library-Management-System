
-- =========================================
-- BOOKNEST - LIBRARY MANAGEMENT SYSTEM
-- PHASE 2: TRIGGERS
-- =========================================

-- TRIGGER 1: UPDATE BOOK COPY STATUS
-- WHEN A BOOK IS ISSUED

CREATE OR REPLACE TRIGGER TRG_BOOK_ISSUED
AFTER INSERT ON ISSUE
FOR EACH ROW
BEGIN
    UPDATE BOOK_COPY
    SET STATUS = 'ISSUED'
    WHERE COPY_ID = :NEW.COPY_ID;
END;
/

-- TRIGGER 2: UPDATE ISSUE AND COPY STATUS
-- WHEN A BOOK IS RETURNED

CREATE OR REPLACE TRIGGER TRG_BOOK_RETURNED
AFTER INSERT ON BOOK_RETURN
FOR EACH ROW
DECLARE
    V_COPY_ID NUMBER;
BEGIN
    -- Find the copy linked to this issue
    SELECT COPY_ID
    INTO V_COPY_ID
    FROM ISSUE
    WHERE ISSUE_ID = :NEW.ISSUE_ID;

    -- Mark issue as returned
    UPDATE ISSUE
    SET ISSUE_STATUS = 'RETURNED'
    WHERE ISSUE_ID = :NEW.ISSUE_ID;

    -- Make the book copy available again
    UPDATE BOOK_COPY
    SET STATUS = 'AVAILABLE'
    WHERE COPY_ID = V_COPY_ID;
END;
/
