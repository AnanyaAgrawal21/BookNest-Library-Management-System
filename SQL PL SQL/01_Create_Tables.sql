
-- =========================================
-- BOOKNEST - LIBRARY MANAGEMENT SYSTEM
-- PHASE 2: DATABASE TABLE CREATION
-- =========================================

-- 1. CATEGORY TABLE
CREATE TABLE CATEGORY (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(500)
);

-- 2. BOOK TABLE
CREATE TABLE BOOK (
    BOOK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ISBN VARCHAR2(20) NOT NULL UNIQUE,
    TITLE VARCHAR2(200) NOT NULL,
    PUBLISHER VARCHAR2(150),
    PUBLICATION_YEAR NUMBER(4),
    PRICE NUMBER(10,2),
    CATEGORY_ID NUMBER NOT NULL,

    CONSTRAINT FK_BOOK_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORY(CATEGORY_ID),

    CONSTRAINT CHK_BOOK_PRICE
        CHECK (PRICE >= 0)
);

-- 3. AUTHOR TABLE
CREATE TABLE AUTHOR (
    AUTHOR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUTHOR_NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150),
    COUNTRY VARCHAR2(100)
);

-- 4. BOOK_AUTHOR TABLE
CREATE TABLE BOOK_AUTHOR (
    BOOK_ID NUMBER NOT NULL,
    AUTHOR_ID NUMBER NOT NULL,

    PRIMARY KEY (BOOK_ID, AUTHOR_ID),

    FOREIGN KEY (BOOK_ID)
        REFERENCES BOOK(BOOK_ID),

    FOREIGN KEY (AUTHOR_ID)
        REFERENCES AUTHOR(AUTHOR_ID)
);

-- 5. BOOK_COPY TABLE
CREATE TABLE BOOK_COPY (
    COPY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOK_ID NUMBER NOT NULL,
    COPY_NUMBER NUMBER NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'AVAILABLE',
    SHELF_LOCATION VARCHAR2(50),
    ACQUISITION_DATE DATE,

    CONSTRAINT FK_COPY_BOOK
        FOREIGN KEY (BOOK_ID)
        REFERENCES BOOK(BOOK_ID),

    CONSTRAINT UQ_BOOK_COPY
        UNIQUE (BOOK_ID, COPY_NUMBER),

    CONSTRAINT CHK_COPY_STATUS
        CHECK (STATUS IN ('AVAILABLE', 'ISSUED', 'DAMAGED'))
);

-- 6. MEMBER TABLE
CREATE TABLE MEMBER (
    MEMBER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PHONE VARCHAR2(15),
    ADDRESS VARCHAR2(300),
    REGISTRATION_DATE DATE DEFAULT SYSDATE
);

-- 7. LIBRARIAN TABLE
CREATE TABLE LIBRARIAN (
    LIBRARIAN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PHONE VARCHAR2(15)
);

-- 8. ISSUE TABLE
CREATE TABLE ISSUE (
    ISSUE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COPY_ID NUMBER NOT NULL,
    MEMBER_ID NUMBER NOT NULL,
    LIBRARIAN_ID NUMBER NOT NULL,
    ISSUE_DATE DATE DEFAULT SYSDATE,
    DUE_DATE DATE NOT NULL,
    ISSUE_STATUS VARCHAR2(20) DEFAULT 'ISSUED',

    CONSTRAINT FK_ISSUE_COPY
        FOREIGN KEY (COPY_ID)
        REFERENCES BOOK_COPY(COPY_ID),

    CONSTRAINT FK_ISSUE_MEMBER
        FOREIGN KEY (MEMBER_ID)
        REFERENCES MEMBER(MEMBER_ID),

    CONSTRAINT FK_ISSUE_LIBRARIAN
        FOREIGN KEY (LIBRARIAN_ID)
        REFERENCES LIBRARIAN(LIBRARIAN_ID),

    CONSTRAINT CHK_ISSUE_STATUS
        CHECK (ISSUE_STATUS IN ('ISSUED', 'RETURNED'))
);

-- 9. BOOK_RETURN TABLE
CREATE TABLE BOOK_RETURN (
    RETURN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ISSUE_ID NUMBER NOT NULL UNIQUE,
    RETURN_DATE DATE DEFAULT SYSDATE,
    BOOK_CONDITION VARCHAR2(50),

    CONSTRAINT FK_RETURN_ISSUE
        FOREIGN KEY (ISSUE_ID)
        REFERENCES ISSUE(ISSUE_ID)
);

-- 10. FINE TABLE
CREATE TABLE FINE (
    FINE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RETURN_ID NUMBER NOT NULL UNIQUE,
    AMOUNT NUMBER(10,2) DEFAULT 0,
    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'UNPAID',
    PAYMENT_DATE DATE,

    CONSTRAINT FK_FINE_RETURN
        FOREIGN KEY (RETURN_ID)
        REFERENCES BOOK_RETURN(RETURN_ID),

    CONSTRAINT CHK_FINE_AMOUNT
        CHECK (AMOUNT >= 0),

    CONSTRAINT CHK_PAYMENT_STATUS
        CHECK (PAYMENT_STATUS IN ('PAID', 'UNPAID'))
);

-- CHECK ALL CREATED TABLES
SELECT TABLE_NAME
FROM USER_TABLES
ORDER BY TABLE_NAME;
