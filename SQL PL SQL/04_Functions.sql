-- FUNCTION 1: CALCULATE FINE

CREATE OR REPLACE FUNCTION CALCULATE_FINE (
    P_ISSUE_ID IN NUMBER
)
RETURN NUMBER
AS
    V_DUE_DATE DATE;
    V_FINE NUMBER;
BEGIN
    SELECT DUE_DATE
    INTO V_DUE_DATE
    FROM ISSUE
    WHERE ISSUE_ID = P_ISSUE_ID;

    V_FINE := GREATEST(
        TRUNC(SYSDATE) - TRUNC(V_DUE_DATE),
        0
    ) * 10;

    RETURN V_FINE;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;
/

-- FUNCTION 2: AVAILABLE COPIES

CREATE OR REPLACE FUNCTION AVAILABLE_COPIES (
    P_BOOK_ID IN NUMBER
)
RETURN NUMBER
AS
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_COUNT
    FROM BOOK_COPY
    WHERE BOOK_ID = P_BOOK_ID
      AND STATUS = 'AVAILABLE';

    RETURN V_COUNT;
END;
/
