-- REPORT 1: DISPLAY ALL BOOKS WITH CATEGORY
SELECT
    B.BOOK_ID,
    B.ISBN,
    B.TITLE,
    B.PUBLISHER,
    B.PUBLICATION_YEAR,
    B.PRICE,
    C.CATEGORY_NAME
FROM BOOK B
JOIN CATEGORY C
ON B.CATEGORY_ID = C.CATEGORY_ID
ORDER BY B.TITLE;


-- REPORT 2: BOOKS WITH THEIR AUTHORS
SELECT
    B.TITLE,
    A.AUTHOR_NAME,
    A.COUNTRY
FROM BOOK B
JOIN BOOK_AUTHOR BA
ON B.BOOK_ID = BA.BOOK_ID
JOIN AUTHOR A
ON BA.AUTHOR_ID = A.AUTHOR_ID
ORDER BY B.TITLE;


-- REPORT 3: AVAILABLE COPIES OF EACH BOOK
SELECT
    B.BOOK_ID,
    B.TITLE,
    COUNT(BC.COPY_ID) AS AVAILABLE_COPIES
FROM BOOK B
LEFT JOIN BOOK_COPY BC
ON B.BOOK_ID = BC.BOOK_ID
AND BC.STATUS = 'AVAILABLE'
GROUP BY B.BOOK_ID, B.TITLE
ORDER BY B.TITLE;


-- REPORT 4: COMPLETE BOOK ISSUE HISTORY
SELECT
    I.ISSUE_ID,
    B.TITLE,
    M.NAME AS MEMBER_NAME,
    L.NAME AS LIBRARIAN_NAME,
    I.ISSUE_DATE,
    I.DUE_DATE,
    I.ISSUE_STATUS
FROM ISSUE I
JOIN BOOK_COPY BC
ON I.COPY_ID = BC.COPY_ID
JOIN BOOK B
ON BC.BOOK_ID = B.BOOK_ID
JOIN MEMBER M
ON I.MEMBER_ID = M.MEMBER_ID
JOIN LIBRARIAN L
ON I.LIBRARIAN_ID = L.LIBRARIAN_ID
ORDER BY I.ISSUE_DATE DESC;


-- REPORT 5: CURRENTLY ISSUED BOOKS
SELECT
    B.TITLE,
    M.NAME AS MEMBER_NAME,
    I.ISSUE_DATE,
    I.DUE_DATE
FROM ISSUE I
JOIN BOOK_COPY BC
ON I.COPY_ID = BC.COPY_ID
JOIN BOOK B
ON BC.BOOK_ID = B.BOOK_ID
JOIN MEMBER M
ON I.MEMBER_ID = M.MEMBER_ID
WHERE I.ISSUE_STATUS = 'ISSUED'
ORDER BY I.DUE_DATE;


-- REPORT 6: OVERDUE BOOKS
SELECT
    I.ISSUE_ID,
    B.TITLE,
    M.NAME AS MEMBER_NAME,
    I.DUE_DATE,
    TRUNC(SYSDATE) - TRUNC(I.DUE_DATE) AS DAYS_OVERDUE
FROM ISSUE I
JOIN BOOK_COPY BC
ON I.COPY_ID = BC.COPY_ID
JOIN BOOK B
ON BC.BOOK_ID = B.BOOK_ID
JOIN MEMBER M
ON I.MEMBER_ID = M.MEMBER_ID
WHERE I.ISSUE_STATUS = 'ISSUED'
AND I.DUE_DATE < TRUNC(SYSDATE)
ORDER BY I.DUE_DATE;


-- REPORT 7: FINE DETAILS
SELECT
    F.FINE_ID,
    B.TITLE,
    M.NAME AS MEMBER_NAME,
    BR.RETURN_DATE,
    F.AMOUNT,
    F.PAYMENT_STATUS,
    F.PAYMENT_DATE
FROM FINE F
JOIN BOOK_RETURN BR
ON F.RETURN_ID = BR.RETURN_ID
JOIN ISSUE I
ON BR.ISSUE_ID = I.ISSUE_ID
JOIN BOOK_COPY BC
ON I.COPY_ID = BC.COPY_ID
JOIN BOOK B
ON BC.BOOK_ID = B.BOOK_ID
JOIN MEMBER M
ON I.MEMBER_ID = M.MEMBER_ID
ORDER BY F.AMOUNT DESC;


-- REPORT 8: TOTAL BOOKS AND COPIES
SELECT
    (SELECT COUNT(*) FROM BOOK) AS TOTAL_BOOKS,
    (SELECT COUNT(*) FROM BOOK_COPY) AS TOTAL_COPIES,
    (SELECT COUNT(*) FROM BOOK_COPY
     WHERE STATUS = 'AVAILABLE') AS AVAILABLE_COPIES,
    (SELECT COUNT(*) FROM BOOK_COPY
     WHERE STATUS = 'ISSUED') AS ISSUED_COPIES
FROM DUAL;


-- REPORT 9: TOTAL FINE COLLECTION
SELECT
    NVL(SUM(AMOUNT), 0) AS TOTAL_FINE_AMOUNT,
    NVL(SUM(
        CASE
            WHEN PAYMENT_STATUS = 'PAID'
            THEN AMOUNT
            ELSE 0
        END
    ), 0) AS PAID_FINE_AMOUNT,
    NVL(SUM(
        CASE
            WHEN PAYMENT_STATUS = 'UNPAID'
            THEN AMOUNT
            ELSE 0
        END
    ), 0) AS UNPAID_FINE_AMOUNT
FROM FINE;


-- REPORT 10: MEMBER REGISTRATION REPORT
SELECT
    MEMBER_ID,
    NAME,
    EMAIL,
    PHONE,
    REGISTRATION_DATE
FROM MEMBER
ORDER BY REGISTRATION_DATE DESC;
